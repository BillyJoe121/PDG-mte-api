-- V19's initiative_execution_entry references project, the legacy V1 domain.
-- Keep its rows and foreign key intact; V2 execution belongs to initiative.
CREATE TABLE initiative_execution_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    initiative_id BIGINT NOT NULL REFERENCES initiative(id),
    actor_id BIGINT NOT NULL REFERENCES professor(id),
    execution_date DATE NOT NULL,
    summary TEXT NOT NULL,
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_initiative_execution_log_history ON initiative_execution_log(initiative_id, execution_date DESC, id DESC);
