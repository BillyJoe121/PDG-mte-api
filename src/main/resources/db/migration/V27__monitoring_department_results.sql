-- Required participants are captured when validating and materialized with the branches.
CREATE TABLE IF NOT EXISTS monitoring_department_result (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  branch_id BIGINT NOT NULL REFERENCES monitoring_branch(id),
  department_id BIGINT NOT NULL REFERENCES department(id),
  department_name VARCHAR(255) NOT NULL,
  version BIGINT NOT NULL DEFAULT 0,
  entry_id BIGINT REFERENCES monitoring_entry(id),
  submitted_at TIMESTAMPTZ,
  submitted_by BIGINT REFERENCES professor(id),
  UNIQUE(branch_id,department_id)
);
CREATE TABLE IF NOT EXISTS monitoring_department_delivery (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  result_id BIGINT NOT NULL REFERENCES monitoring_department_result(id),
  version BIGINT NOT NULL,
  entry_id BIGINT NOT NULL REFERENCES monitoring_entry(id),
  actor_id BIGINT NOT NULL REFERENCES professor(id),
  submitted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE(result_id,version)
);
