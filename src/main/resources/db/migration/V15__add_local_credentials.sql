-- Accounts, single-use access links and closed sessions are kept in the MTE database.
CREATE TABLE IF NOT EXISTS auth_credential (
    user_id UUID PRIMARY KEY,
    password_hash VARCHAR(100),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE IF NOT EXISTS auth_link_token (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash VARCHAR(64) NOT NULL,
    user_id UUID NOT NULL,
    link_type VARCHAR(16) NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    used_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_auth_link_token_token_hash UNIQUE (token_hash),
    CONSTRAINT fk_auth_link_token_credential
        FOREIGN KEY (user_id) REFERENCES auth_credential (user_id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_auth_link_token_user_id ON auth_link_token (user_id);

CREATE TABLE IF NOT EXISTS auth_revoked_token (
    token_id VARCHAR(64) PRIMARY KEY,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_auth_revoked_token_expires_at ON auth_revoked_token (expires_at);

-- People already linked to an account keep their id; they set a password with a new access link.
INSERT INTO auth_credential (user_id, password_hash, created_at, updated_at)
SELECT p.auth_user_id, NULL, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP
FROM professor p
WHERE p.auth_user_id IS NOT NULL
ON CONFLICT (user_id) DO NOTHING;
