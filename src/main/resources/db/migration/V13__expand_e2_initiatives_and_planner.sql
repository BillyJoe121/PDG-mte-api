-- 1. Operational Initiatives (HT-023, HT-026, HT-027, HT-028)
CREATE TABLE IF NOT EXISTS initiative (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  key_result_id BIGINT NOT NULL REFERENCES key_result(id) ON DELETE CASCADE,
  department_id BIGINT NOT NULL REFERENCES department(id),
  title VARCHAR(255) NOT NULL,
  description TEXT NOT NULL,
  status VARCHAR(32) NOT NULL DEFAULT 'DRAFT',
  progress_percent NUMERIC(5,2) CHECK (progress_percent BETWEEN 0 AND 100),
  version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0),
  active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_initiative_kr ON initiative(key_result_id);
CREATE INDEX IF NOT EXISTS idx_initiative_dept_status ON initiative(department_id, status);

-- 2. Initiative Assignment history (HT-023, HT-030, AD-2, AD-6)
CREATE TABLE IF NOT EXISTS initiative_assignment (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  initiative_id BIGINT NOT NULL REFERENCES initiative(id) ON DELETE CASCADE,
  professor_id BIGINT NOT NULL REFERENCES professor(id),
  started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  ended_at TIMESTAMPTZ,
  actor_id BIGINT NOT NULL REFERENCES professor(id),
  CHECK (ended_at IS NULL OR ended_at > started_at)
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_initiative_owner_active ON initiative_assignment(initiative_id) WHERE ended_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_initiative_asgn_prof ON initiative_assignment(professor_id) WHERE ended_at IS NULL;

-- 3. Initiative manual progress entries (HT-026, HT-028, AD-4)
CREATE TABLE IF NOT EXISTS initiative_progress_entry (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  initiative_id BIGINT NOT NULL REFERENCES initiative(id) ON DELETE CASCADE,
  progress_percent NUMERIC(5,2) NOT NULL CHECK (progress_percent BETWEEN 0 AND 100),
  status VARCHAR(32) NOT NULL,
  comment TEXT NOT NULL,
  actor_id BIGINT NOT NULL REFERENCES professor(id),
  occurred_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  supersedes_id BIGINT REFERENCES initiative_progress_entry(id)
);

CREATE INDEX IF NOT EXISTS idx_initiative_progress_entry ON initiative_progress_entry(initiative_id);

-- 4. Microsoft Planner connections (HT-019, HT-020, HT-030, AD-3, AD-9)
CREATE TABLE IF NOT EXISTS planner_connection (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  professor_id BIGINT NOT NULL REFERENCES professor(id),
  provider VARCHAR(32) NOT NULL CHECK (provider = 'MICROSOFT_GRAPH'),
  external_tenant_id TEXT NOT NULL,
  granted_scopes TEXT NOT NULL,
  consent_status VARCHAR(24) NOT NULL,
  secret_ref TEXT NOT NULL,
  last_synced_at TIMESTAMPTZ,
  revoked_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_planner_connection_active ON planner_connection(professor_id) 
  WHERE revoked_at IS NULL AND consent_status = 'ACTIVE';

-- 5. Planner synchronization run logs (HT-021, HT-025, HT-030, AD-2, AD-9)
CREATE TABLE IF NOT EXISTS planner_sync_run (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  connection_id BIGINT NOT NULL REFERENCES planner_connection(id) ON DELETE CASCADE,
  state VARCHAR(24) NOT NULL,
  started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  finished_at TIMESTAMPTZ,
  error_code VARCHAR(64)
);

CREATE INDEX IF NOT EXISTS idx_planner_sync_run_conn ON planner_sync_run(connection_id);

-- 6. External Planner Task References (HT-024, HT-025, HT-026, HT-030, AD-4, AD-9)
CREATE TABLE IF NOT EXISTS planner_task_ref (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  connection_id BIGINT NOT NULL REFERENCES planner_connection(id),
  initiative_id BIGINT NOT NULL REFERENCES initiative(id) ON DELETE CASCADE,
  provider VARCHAR(32) NOT NULL CHECK (provider = 'MICROSOFT_GRAPH'),
  external_plan_id TEXT NOT NULL,
  external_task_id TEXT NOT NULL,
  external_url TEXT,
  linked_by BIGINT NOT NULL REFERENCES professor(id),
  title_snapshot TEXT,
  bucket_snapshot TEXT,
  status_snapshot VARCHAR(32),
  due_date_snapshot TIMESTAMPTZ,
  last_synced_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_planner_task_initiative ON planner_task_ref(connection_id, external_task_id, initiative_id);
CREATE INDEX IF NOT EXISTS idx_planner_task_ref_init ON planner_task_ref(initiative_id);

-- 7. Legacy project migration runs and exception management (HT-029, AD-5, AD-6)
CREATE TABLE IF NOT EXISTS migration_run (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source VARCHAR(64) NOT NULL,
  status VARCHAR(24) NOT NULL,
  started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  finished_at TIMESTAMPTZ,
  checksum CHAR(64)
);

CREATE TABLE IF NOT EXISTS migration_exception (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_id BIGINT NOT NULL REFERENCES migration_run(id) ON DELETE CASCADE,
  legacy_type VARCHAR(32) NOT NULL,
  legacy_id BIGINT NOT NULL,
  reason_code VARCHAR(64) NOT NULL,
  resolved_at TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS idx_migration_exception_run ON migration_exception(run_id);
