ALTER TABLE corrective_action ADD COLUMN IF NOT EXISTS version BIGINT NOT NULL DEFAULT 0;
CREATE TABLE IF NOT EXISTS corrective_action_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  corrective_action_id BIGINT NOT NULL REFERENCES corrective_action(id),
  previous_status VARCHAR(24) NOT NULL,
  new_status VARCHAR(24) NOT NULL,
  comment TEXT NOT NULL,
  evidence_id BIGINT REFERENCES evidence(id),
  actor_id BIGINT NOT NULL REFERENCES professor(id),
  changed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_corrective_history_action ON corrective_action_history(corrective_action_id);
