-- 1. KR Measurement / Check-ins (HT-031)
CREATE TABLE IF NOT EXISTS kr_measurement (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  key_result_id BIGINT NOT NULL REFERENCES key_result(id) ON DELETE CASCADE,
  measured_value NUMERIC(12, 4) NOT NULL,
  observed_at TIMESTAMP WITH TIME ZONE NOT NULL,
  comment TEXT,
  registered_by VARCHAR(100) NOT NULL,
  registered_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  status VARCHAR(24) NOT NULL DEFAULT 'ACTIVE',
  version BIGINT NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS idx_kr_measurement_kr ON kr_measurement(key_result_id);
CREATE INDEX IF NOT EXISTS idx_kr_measurement_observed ON kr_measurement(observed_at);

-- 2. Evidence of check-ins and initiatives (HT-032)
CREATE TABLE IF NOT EXISTS evidence (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  measurement_id BIGINT REFERENCES kr_measurement(id) ON DELETE CASCADE,
  initiative_id BIGINT REFERENCES initiative(id) ON DELETE SET NULL,
  title VARCHAR(255) NOT NULL,
  evidence_type VARCHAR(50) NOT NULL,
  external_ref VARCHAR(1000),
  file_hash_sha256 VARCHAR(64),
  active BOOLEAN NOT NULL DEFAULT TRUE,
  created_by VARCHAR(100) NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_evidence_measurement ON evidence(measurement_id);
CREATE INDEX IF NOT EXISTS idx_evidence_initiative ON evidence(initiative_id);

-- 3. Key Result manual progress declarations (HT-033, HT-034)
CREATE TABLE IF NOT EXISTS kr_progress_entry (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  key_result_id BIGINT NOT NULL REFERENCES key_result(id) ON DELETE CASCADE,
  progress_percent NUMERIC(5, 2) NOT NULL CHECK (progress_percent >= 0 AND progress_percent <= 100),
  status VARCHAR(24) NOT NULL DEFAULT 'ON_TRACK',
  comment TEXT,
  declared_by VARCHAR(100) NOT NULL,
  declared_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_kr_progress_kr ON kr_progress_entry(key_result_id);
CREATE INDEX IF NOT EXISTS idx_kr_progress_declared ON kr_progress_entry(declared_at);

-- 4. Key Result qualitative confidence declarations (HT-035)
CREATE TABLE IF NOT EXISTS kr_confidence_entry (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  key_result_id BIGINT NOT NULL REFERENCES key_result(id) ON DELETE CASCADE,
  confidence_level VARCHAR(20) NOT NULL,
  comment TEXT NOT NULL,
  author_id VARCHAR(100) NOT NULL,
  recorded_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_kr_confidence_kr ON kr_confidence_entry(key_result_id);

-- 5. KR Target Revisions (HT-039)
CREATE TABLE IF NOT EXISTS kr_target_revision (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  key_result_id BIGINT NOT NULL REFERENCES key_result(id) ON DELETE CASCADE,
  previous_baseline NUMERIC(12, 4) NOT NULL,
  new_baseline NUMERIC(12, 4) NOT NULL,
  previous_target NUMERIC(12, 4) NOT NULL,
  new_target NUMERIC(12, 4) NOT NULL,
  reason TEXT NOT NULL,
  effective_from_check_in VARCHAR(100),
  approval_status VARCHAR(30) NOT NULL DEFAULT 'PENDING',
  policy_unset BOOLEAN NOT NULL DEFAULT FALSE,
  approved_by VARCHAR(100),
  approved_at TIMESTAMP WITH TIME ZONE,
  requested_by VARCHAR(100) NOT NULL,
  requested_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_kr_target_revision_kr ON kr_target_revision(key_result_id);

-- 6. Monitoring cut & Rector Review (HT-040)
CREATE TABLE IF NOT EXISTS monitoring_cut (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cycle_id BIGINT NOT NULL REFERENCES strategic_cycle(id) ON DELETE CASCADE,
  cut_code VARCHAR(50) NOT NULL,
  cut_date DATE NOT NULL,
  status VARCHAR(24) NOT NULL DEFAULT 'OPEN',
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_monitoring_cut_cycle ON monitoring_cut(cycle_id);

CREATE TABLE IF NOT EXISTS rector_review (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  monitoring_cut_id BIGINT NOT NULL REFERENCES monitoring_cut(id) ON DELETE CASCADE,
  review_version INTEGER NOT NULL DEFAULT 1,
  status VARCHAR(24) NOT NULL DEFAULT 'APPROVED',
  reviewed_by VARCHAR(100) NOT NULL,
  reviewed_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  observations TEXT
);

CREATE INDEX IF NOT EXISTS idx_rector_review_cut ON rector_review(monitoring_cut_id);

-- 7. Strategic Cycle Closure & Snapshot (HT-040)
CREATE TABLE IF NOT EXISTS cycle_closure (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cycle_id BIGINT NOT NULL UNIQUE REFERENCES strategic_cycle(id) ON DELETE CASCADE,
  rector_review_id BIGINT REFERENCES rector_review(id),
  closure_status VARCHAR(24) NOT NULL DEFAULT 'CLOSED',
  closed_by VARCHAR(100) NOT NULL,
  closed_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  retrospective_achievements TEXT NOT NULL,
  retrospective_causes TEXT NOT NULL,
  retrospective_learnings TEXT NOT NULL,
  retrospective_continuity TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS cycle_closure_snapshot (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cycle_closure_id BIGINT NOT NULL REFERENCES cycle_closure(id) ON DELETE CASCADE,
  key_result_id BIGINT NOT NULL REFERENCES key_result(id),
  kr_name VARCHAR(255) NOT NULL,
  final_measured_value NUMERIC(12, 4),
  final_manual_progress NUMERIC(5, 2) NOT NULL,
  final_status VARCHAR(24) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_closure_snapshot_closure ON cycle_closure_snapshot(cycle_closure_id);
