-- 1. Report Export Audit Registry (HT-052)
CREATE TABLE IF NOT EXISTS report_export (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  report_type VARCHAR(50) NOT NULL,
  cut_id BIGINT REFERENCES monitoring_cut(id),
  cycle_id BIGINT REFERENCES strategic_cycle(id),
  key_result_id BIGINT REFERENCES key_result(id),
  exported_by VARCHAR(100) NOT NULL,
  filters_applied TEXT,
  file_format VARCHAR(20) NOT NULL,
  file_size_bytes BIGINT,
  file_sha256 VARCHAR(64),
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_report_export_user ON report_export(exported_by);
CREATE INDEX IF NOT EXISTS idx_report_export_cut ON report_export(cut_id);

-- 2. School Final Period Report (HT-054)
CREATE TABLE IF NOT EXISTS school_final_report (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cycle_id BIGINT NOT NULL REFERENCES strategic_cycle(id) ON DELETE CASCADE,
  department_id BIGINT REFERENCES department(id),
  title VARCHAR(255) NOT NULL,
  executive_summary TEXT NOT NULL,
  achievements_summary TEXT NOT NULL,
  challenges_summary TEXT NOT NULL,
  status VARCHAR(24) NOT NULL DEFAULT 'DRAFT',
  author_id VARCHAR(100) NOT NULL,
  submitted_at TIMESTAMP WITH TIME ZONE,
  approved_by VARCHAR(100),
  approved_at TIMESTAMP WITH TIME ZONE,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_school_final_report_cycle ON school_final_report(cycle_id);

-- 3. Interactive Presentation Session (HT-054)
CREATE TABLE IF NOT EXISTS presentation_session (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cycle_id BIGINT NOT NULL REFERENCES strategic_cycle(id),
  cut_id BIGINT REFERENCES monitoring_cut(id),
  presenter_id VARCHAR(100) NOT NULL,
  title VARCHAR(255) NOT NULL,
  active_slide VARCHAR(50) NOT NULL DEFAULT 'SUMMARY',
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_presentation_session_cycle ON presentation_session(cycle_id);
