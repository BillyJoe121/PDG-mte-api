-- 1. User roles and strict organizational scope binding (HT-056, HT-057, AD-11)
CREATE TABLE IF NOT EXISTS user_role (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  professor_id BIGINT NOT NULL REFERENCES professor(id),
  role_name VARCHAR(32) NOT NULL CHECK (role_name IN ('ADMIN','RECTOR','DECANO','DIRECTOR','JEFE','RESPONSABLE','AUDITOR')),
  faculty_id BIGINT REFERENCES faculty(id),
  school_id BIGINT REFERENCES school(id),
  department_id BIGINT REFERENCES department(id),
  started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  ended_at TIMESTAMPTZ,
  CHECK (
    (role_name IN ('ADMIN','RECTOR','AUDITOR') AND num_nonnulls(faculty_id, school_id, department_id) = 0)
    OR (role_name = 'DECANO' AND faculty_id IS NOT NULL AND school_id IS NULL AND department_id IS NULL)
    OR (role_name = 'DIRECTOR' AND faculty_id IS NULL AND school_id IS NOT NULL AND department_id IS NULL)
    OR (role_name IN ('JEFE','RESPONSABLE') AND faculty_id IS NULL AND school_id IS NULL AND department_id IS NOT NULL)
  ),
  CHECK (ended_at IS NULL OR ended_at > started_at)
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_user_role_active ON user_role(
  professor_id,
  role_name,
  coalesce(faculty_id, 0),
  coalesce(school_id, 0),
  coalesce(department_id, 0)
) WHERE ended_at IS NULL;

CREATE INDEX IF NOT EXISTS idx_user_role_faculty ON user_role(faculty_id) WHERE ended_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_user_role_school ON user_role(school_id) WHERE ended_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_user_role_department ON user_role(department_id) WHERE ended_at IS NULL;

-- 2. Assignment and role change audit history (HT-058, AD-2, AD-6)
CREATE TABLE IF NOT EXISTS assignment_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entity_type VARCHAR(32) NOT NULL,
  entity_id BIGINT NOT NULL,
  professor_id BIGINT NOT NULL REFERENCES professor(id),
  action VARCHAR(24) NOT NULL,
  actor_id BIGINT NOT NULL REFERENCES professor(id),
  occurred_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_assignment_history_entity ON assignment_history(entity_type, entity_id);
CREATE INDEX IF NOT EXISTS idx_assignment_history_prof ON assignment_history(professor_id);

-- 3. Directory sync runs and conflict tracking (HT-059, AD-2, AD-3)
CREATE TABLE IF NOT EXISTS directory_sync_run (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source VARCHAR(64) NOT NULL,
  status VARCHAR(24) NOT NULL CHECK (status IN ('STARTED','PREVIEW','APPLIED','FAILED')),
  started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  finished_at TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS directory_sync_conflict (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_id BIGINT NOT NULL REFERENCES directory_sync_run(id) ON DELETE CASCADE,
  external_ref TEXT NOT NULL,
  field_name VARCHAR(64) NOT NULL,
  status VARCHAR(24) NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN','RESOLVED','IGNORED')),
  resolution TEXT
);

CREATE INDEX IF NOT EXISTS idx_sync_conflict_run ON directory_sync_conflict(run_id);

-- 4. Server-side session invalidation and tracking (HT-055, HT-060, AD-1, AD-13)
CREATE TABLE IF NOT EXISTS auth_session (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  professor_id BIGINT NOT NULL REFERENCES professor(id),
  token_digest CHAR(64) NOT NULL UNIQUE,
  issued_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  expires_at TIMESTAMPTZ NOT NULL,
  revoked_at TIMESTAMPTZ,
  CHECK (issued_at < expires_at)
);

CREATE INDEX IF NOT EXISTS idx_auth_session_active ON auth_session(professor_id, expires_at) WHERE revoked_at IS NULL;

-- 5. Versioned institutional governance policies (HT-056, HT-060, AD-10, AD-13)
CREATE TABLE IF NOT EXISTS institutional_policy (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  policy_key VARCHAR(64) NOT NULL,
  version INTEGER NOT NULL CHECK (version > 0),
  value JSONB NOT NULL,
  approved_by BIGINT NOT NULL REFERENCES professor(id),
  approved_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  effective_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT uq_institutional_policy_key_version UNIQUE (policy_key, version)
);
