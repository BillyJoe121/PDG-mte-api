-- 1. Extend audit_log with trace and department scope (HT-070, HT-072)
ALTER TABLE audit_log ADD COLUMN IF NOT EXISTS trace_id VARCHAR(100);
ALTER TABLE audit_log ADD COLUMN IF NOT EXISTS department_id BIGINT;

CREATE INDEX IF NOT EXISTS idx_audit_log_trace ON audit_log(trace_id);
CREATE INDEX IF NOT EXISTS idx_audit_log_dept ON audit_log(department_id);

-- 2. Evidence Versioning & Chain of Custody (HT-073)
CREATE TABLE IF NOT EXISTS evidence_version (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  evidence_id BIGINT NOT NULL REFERENCES evidence(id) ON DELETE CASCADE,
  version_number INTEGER NOT NULL DEFAULT 1,
  file_hash_sha256 VARCHAR(64) NOT NULL,
  external_ref VARCHAR(1000),
  captured_by VARCHAR(100) NOT NULL,
  captured_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  notes TEXT
);

CREATE INDEX IF NOT EXISTS idx_evidence_version_evidence ON evidence_version(evidence_id);

-- 3. Audit Retention Policies (HT-074)
CREATE TABLE IF NOT EXISTS retention_policy (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  policy_name VARCHAR(150) NOT NULL,
  entity_scope VARCHAR(100) NOT NULL,
  retention_days INTEGER NOT NULL CHECK (retention_days > 0),
  responsible_role VARCHAR(50) NOT NULL DEFAULT 'ADMIN',
  status VARCHAR(24) NOT NULL DEFAULT 'ACTIVE',
  version INTEGER NOT NULL DEFAULT 1,
  approved_by VARCHAR(100),
  approved_at TIMESTAMP WITH TIME ZONE,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 4. Legal Holds against Purge (HT-074)
CREATE TABLE IF NOT EXISTS retention_hold (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entity_type VARCHAR(100) NOT NULL,
  entity_id VARCHAR(100) NOT NULL,
  reason TEXT NOT NULL,
  hold_status VARCHAR(24) NOT NULL DEFAULT 'ACTIVE',
  applied_by VARCHAR(100) NOT NULL,
  applied_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  released_by VARCHAR(100),
  released_at TIMESTAMP WITH TIME ZONE
);

CREATE INDEX IF NOT EXISTS idx_retention_hold_entity ON retention_hold(entity_type, entity_id);

-- 5. Audit Export Manifests (HT-074)
CREATE TABLE IF NOT EXISTS audit_export (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  exported_by VARCHAR(100) NOT NULL,
  filters_applied TEXT,
  date_from TIMESTAMP WITH TIME ZONE,
  date_to TIMESTAMP WITH TIME ZONE,
  total_records_exported INTEGER NOT NULL,
  file_format VARCHAR(20) NOT NULL DEFAULT 'CSV',
  file_sha256 VARCHAR(64),
  exported_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
