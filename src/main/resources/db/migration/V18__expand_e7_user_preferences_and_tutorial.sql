-- 1. User Tutorial Progress (HT-064)
CREATE TABLE IF NOT EXISTS user_tutorial_progress (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id VARCHAR(100) NOT NULL,
  role_context VARCHAR(50) NOT NULL,
  current_step_index INTEGER NOT NULL DEFAULT 0,
  completed_steps_json TEXT NOT NULL DEFAULT '[]',
  is_completed BOOLEAN NOT NULL DEFAULT FALSE,
  is_skipped BOOLEAN NOT NULL DEFAULT FALSE,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_user_tutorial_role UNIQUE (user_id, role_context)
);

CREATE INDEX IF NOT EXISTS idx_tutorial_user ON user_tutorial_progress(user_id);

-- 2. User UI Preferences (HT-063, HT-065, HT-066)
CREATE TABLE IF NOT EXISTS user_ui_preference (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id VARCHAR(100) NOT NULL UNIQUE,
  reduced_motion BOOLEAN NOT NULL DEFAULT FALSE,
  high_contrast BOOLEAN NOT NULL DEFAULT FALSE,
  preferred_view_mode VARCHAR(30) NOT NULL DEFAULT 'EXECUTIVE',
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_ui_pref_user ON user_ui_preference(user_id);
