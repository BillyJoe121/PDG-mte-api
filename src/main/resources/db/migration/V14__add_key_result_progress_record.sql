CREATE TABLE IF NOT EXISTS key_result_progress_record (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    key_result_id BIGINT NOT NULL,
    previous_value NUMERIC(12, 2),
    current_value NUMERIC(12, 2) NOT NULL,
    previous_percentage NUMERIC(10, 2),
    progress_percentage NUMERIC(10, 2) NOT NULL,
    author_name VARCHAR(255),
    author_email VARCHAR(255),
    recorded_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_key_result_progress_record_key_result
        FOREIGN KEY (key_result_id) REFERENCES key_result (id)
);

CREATE INDEX IF NOT EXISTS idx_key_result_progress_record_key_result_recorded
    ON key_result_progress_record (key_result_id, recorded_at DESC);
