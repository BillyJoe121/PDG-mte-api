-- 1. Saved User Views & Filter Presets (HT-044)
CREATE TABLE IF NOT EXISTS saved_view (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id VARCHAR(100) NOT NULL,
  name VARCHAR(150) NOT NULL,
  description VARCHAR(255),
  filters_json TEXT NOT NULL,
  view_mode VARCHAR(30) NOT NULL DEFAULT 'EXECUTIVE',
  is_default BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_saved_view_user ON saved_view(user_id);

-- 2. Situations, Risks and Attention (HT-045, HT-049)
CREATE TABLE IF NOT EXISTS situation (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  origin_type VARCHAR(50) NOT NULL,
  origin_id BIGINT,
  department_id BIGINT REFERENCES department(id),
  cycle_id BIGINT REFERENCES strategic_cycle(id),
  severity VARCHAR(20) NOT NULL DEFAULT 'MEDIUM',
  status VARCHAR(24) NOT NULL DEFAULT 'OPEN',
  title VARCHAR(255) NOT NULL,
  description TEXT NOT NULL,
  identified_by VARCHAR(100) NOT NULL,
  identified_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  resolved_at TIMESTAMP WITH TIME ZONE,
  resolution_comment TEXT
);

CREATE INDEX IF NOT EXISTS idx_situation_dept ON situation(department_id);
CREATE INDEX IF NOT EXISTS idx_situation_cycle ON situation(cycle_id);
CREATE INDEX IF NOT EXISTS idx_situation_status ON situation(status);

-- 3. Situation History (HT-045)
CREATE TABLE IF NOT EXISTS situation_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  situation_id BIGINT NOT NULL REFERENCES situation(id) ON DELETE CASCADE,
  previous_status VARCHAR(24) NOT NULL,
  new_status VARCHAR(24) NOT NULL,
  comment TEXT,
  evidence_id BIGINT REFERENCES evidence(id),
  changed_by VARCHAR(100) NOT NULL,
  changed_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_situation_history_situation ON situation_history(situation_id);

-- 4. Departmental Corrective Actions (HT-049)
CREATE TABLE IF NOT EXISTS corrective_action (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  situation_id BIGINT NOT NULL REFERENCES situation(id) ON DELETE CASCADE,
  department_id BIGINT NOT NULL REFERENCES department(id),
  assigned_to VARCHAR(100) NOT NULL,
  due_at DATE NOT NULL,
  decision_description TEXT NOT NULL,
  status VARCHAR(24) NOT NULL DEFAULT 'PENDING',
  evidence_id BIGINT REFERENCES evidence(id),
  created_by VARCHAR(100) NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  closed_at TIMESTAMP WITH TIME ZONE
);

CREATE INDEX IF NOT EXISTS idx_corrective_action_situation ON corrective_action(situation_id);
CREATE INDEX IF NOT EXISTS idx_corrective_action_dept ON corrective_action(department_id);

-- 5. Institutional Policies & Guardrails (HT-048, HT-050)
CREATE TABLE IF NOT EXISTS institutional_policy (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  policy_code VARCHAR(100) NOT NULL UNIQUE,
  name VARCHAR(255) NOT NULL,
  description TEXT,
  status VARCHAR(24) NOT NULL DEFAULT 'ACTIVE',
  config_json TEXT NOT NULL,
  version INTEGER NOT NULL DEFAULT 1,
  approved_by VARCHAR(100),
  approved_at TIMESTAMP WITH TIME ZONE,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_inst_policy_code ON institutional_policy(policy_code);
