-- 1. Strategic Bet extensions (HT-006, HT-017)
ALTER TABLE strategic_bet ADD COLUMN IF NOT EXISTS active BOOLEAN NOT NULL DEFAULT TRUE;
ALTER TABLE strategic_bet ADD COLUMN IF NOT EXISTS version BIGINT NOT NULL DEFAULT 0;

-- 2. Goal extensions (HT-007, HT-017)
ALTER TABLE goal ADD COLUMN IF NOT EXISTS active BOOLEAN NOT NULL DEFAULT TRUE;
ALTER TABLE goal ADD COLUMN IF NOT EXISTS version BIGINT NOT NULL DEFAULT 0;
ALTER TABLE goal ADD COLUMN IF NOT EXISTS responsible_id BIGINT REFERENCES professor(id);

-- 3. Key Result decoupling from Objective & lifecycle expansions (HT-008, HT-010, HT-011, HT-014, AD-8)
ALTER TABLE key_result ALTER COLUMN objective_id DROP NOT NULL;
ALTER TABLE key_result ADD COLUMN IF NOT EXISTS metric_definition_id BIGINT REFERENCES metric_definition(id);
ALTER TABLE key_result ADD COLUMN IF NOT EXISTS strategic_cycle_id BIGINT REFERENCES strategic_cycle(id);
ALTER TABLE key_result ADD COLUMN IF NOT EXISTS type VARCHAR(24) DEFAULT 'COMMITTED' CHECK (type IN ('COMMITTED','ASPIRATIONAL','LEARNING'));
ALTER TABLE key_result ADD COLUMN IF NOT EXISTS version BIGINT NOT NULL DEFAULT 0;
ALTER TABLE key_result ADD COLUMN IF NOT EXISTS active BOOLEAN NOT NULL DEFAULT TRUE;

CREATE INDEX IF NOT EXISTS idx_kr_metric_definition ON key_result(metric_definition_id);
CREATE INDEX IF NOT EXISTS idx_kr_strategic_cycle ON key_result(strategic_cycle_id);

-- 4. Direct N:M Links between Key Results and Goals / Bets (HT-008, HT-012, AD-5)
CREATE TABLE IF NOT EXISTS kr_goal_link (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  key_result_id BIGINT NOT NULL REFERENCES key_result(id) ON DELETE CASCADE,
  goal_id BIGINT NOT NULL REFERENCES goal(id),
  started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  ended_at TIMESTAMPTZ,
  actor_id BIGINT NOT NULL REFERENCES professor(id),
  CHECK (ended_at IS NULL OR ended_at >= started_at)
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_kr_goal_active ON kr_goal_link(key_result_id, goal_id) WHERE ended_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_kr_goal_goal_active ON kr_goal_link(goal_id) WHERE ended_at IS NULL;

CREATE TABLE IF NOT EXISTS kr_bet_link (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  key_result_id BIGINT NOT NULL REFERENCES key_result(id) ON DELETE CASCADE,
  strategic_bet_id BIGINT NOT NULL REFERENCES strategic_bet(id),
  started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  ended_at TIMESTAMPTZ,
  actor_id BIGINT NOT NULL REFERENCES professor(id),
  CHECK (ended_at IS NULL OR ended_at >= started_at)
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_kr_bet_active ON kr_bet_link(key_result_id, strategic_bet_id) WHERE ended_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_kr_bet_bet_active ON kr_bet_link(strategic_bet_id) WHERE ended_at IS NULL;

-- 5. KR Assignment history and ownership intervals (HT-013, AD-2, AD-6)
CREATE TABLE IF NOT EXISTS kr_assignment (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  key_result_id BIGINT NOT NULL REFERENCES key_result(id) ON DELETE CASCADE,
  professor_id BIGINT NOT NULL REFERENCES professor(id),
  started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  ended_at TIMESTAMPTZ,
  actor_id BIGINT NOT NULL REFERENCES professor(id),
  CHECK (ended_at IS NULL OR ended_at > started_at)
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_kr_owner_active ON kr_assignment(key_result_id) WHERE ended_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_kr_assignment_professor_active ON kr_assignment(professor_id) WHERE ended_at IS NULL;

-- 6. Key Result Version snapshots (HT-010, HT-011, HT-014, AD-6)
CREATE TABLE IF NOT EXISTS kr_version (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  key_result_id BIGINT NOT NULL REFERENCES key_result(id) ON DELETE CASCADE,
  version BIGINT NOT NULL CHECK (version >= 0),
  snapshot JSONB NOT NULL,
  reason TEXT NOT NULL,
  actor_id BIGINT NOT NULL REFERENCES professor(id),
  occurred_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT uq_kr_version UNIQUE (key_result_id, version)
);

-- 7. Guardrails and Key Result linkage (HT-015, AD-4, AD-5)
CREATE TABLE IF NOT EXISTS guardrail (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(255) NOT NULL,
  metric_definition_id BIGINT NOT NULL REFERENCES metric_definition(id),
  threshold NUMERIC(18,4) NOT NULL,
  comparison VARCHAR(4) NOT NULL CHECK (comparison IN ('LT','LE','GT','GE')),
  active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS guardrail_kr_link (
  guardrail_id BIGINT NOT NULL REFERENCES guardrail(id) ON DELETE CASCADE,
  key_result_id BIGINT NOT NULL REFERENCES key_result(id) ON DELETE CASCADE,
  PRIMARY KEY (guardrail_id, key_result_id)
);
