-- 1. Faculty entity (HT-003)
CREATE TABLE IF NOT EXISTS faculty (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(255) NOT NULL UNIQUE,
  active BOOLEAN NOT NULL DEFAULT TRUE
);

-- 2. Organization hierarchy extensions (HT-003)
ALTER TABLE school ADD COLUMN IF NOT EXISTS faculty_id BIGINT REFERENCES faculty(id);
ALTER TABLE school ADD COLUMN IF NOT EXISTS active BOOLEAN NOT NULL DEFAULT TRUE;
ALTER TABLE department ADD COLUMN IF NOT EXISTS active BOOLEAN NOT NULL DEFAULT TRUE;
CREATE INDEX IF NOT EXISTS idx_school_faculty ON school(faculty_id);

-- 3. Period lifecycle extensions (HT-001)
ALTER TABLE period ADD COLUMN IF NOT EXISTS active BOOLEAN NOT NULL DEFAULT TRUE;

-- 4. Measurement unit precision & symbol extensions (HT-002)
ALTER TABLE unit_of_measure ADD COLUMN IF NOT EXISTS symbol VARCHAR(32);
ALTER TABLE unit_of_measure ADD COLUMN IF NOT EXISTS decimal_precision SMALLINT NOT NULL DEFAULT 2;
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'ck_uom_precision'
  ) THEN
    ALTER TABLE unit_of_measure ADD CONSTRAINT ck_uom_precision CHECK (decimal_precision BETWEEN 0 AND 6);
  END IF;
END $$;

-- 5. Metric definitions (HT-004)
CREATE TABLE IF NOT EXISTS metric_definition (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(255) NOT NULL,
  unit_of_measure_id BIGINT NOT NULL REFERENCES unit_of_measure(id),
  direction VARCHAR(16) NOT NULL CHECK (direction IN ('INCREASE','DECREASE','MAINTAIN')),
  source_description TEXT NOT NULL,
  version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0),
  frequency_days INTEGER CHECK (frequency_days > 0),
  numerator_description TEXT,
  denominator_description TEXT,
  inclusion_rules TEXT,
  exclusion_rules TEXT,
  active BOOLEAN NOT NULL DEFAULT TRUE,
  CONSTRAINT uq_metric_def_name_uom UNIQUE (name, unit_of_measure_id)
);

-- 6. Strategic cycle & period association (HT-005)
CREATE TABLE IF NOT EXISTS strategic_cycle (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(255) NOT NULL UNIQUE,
  start_date DATE NOT NULL,
  end_date DATE NOT NULL,
  cadence_days INTEGER NOT NULL CHECK (cadence_days > 0),
  status VARCHAR(24) NOT NULL DEFAULT 'DRAFT',
  version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0),
  CONSTRAINT ck_cycle_dates CHECK (start_date <= end_date)
);

CREATE TABLE IF NOT EXISTS strategic_cycle_period (
  cycle_id BIGINT NOT NULL REFERENCES strategic_cycle(id) ON DELETE CASCADE,
  period_id BIGINT NOT NULL REFERENCES period(id),
  PRIMARY KEY (cycle_id, period_id)
);

CREATE INDEX IF NOT EXISTS idx_cycle_period_cycle ON strategic_cycle_period(cycle_id);
CREATE INDEX IF NOT EXISTS idx_cycle_period_period ON strategic_cycle_period(period_id);
