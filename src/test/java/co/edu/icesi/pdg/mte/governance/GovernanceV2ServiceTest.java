package co.edu.icesi.pdg.mte.governance;
import co.edu.icesi.pdg.mte.audit.AuditService;
import co.edu.icesi.pdg.mte.common.BusinessException;
import org.junit.jupiter.api.*;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import java.time.LocalDate;
import java.util.List;
import java.util.UUID;
import static org.assertj.core.api.Assertions.*;
import static org.mockito.Mockito.*;

class GovernanceV2ServiceTest {
    JdbcTemplate jdbc; GovernanceV2Service service;
    @BeforeEach void setup() {
        jdbc = new JdbcTemplate(new DriverManagerDataSource("jdbc:h2:mem:" + UUID.randomUUID() + ";MODE=PostgreSQL;DB_CLOSE_DELAY=-1;DATABASE_TO_LOWER=TRUE", "sa", ""));
        jdbc.execute("CREATE TABLE period(id BIGINT PRIMARY KEY, active BOOLEAN)");
        jdbc.execute("INSERT INTO period VALUES(1,TRUE)");
        jdbc.execute("CREATE TABLE unit_of_measure(id BIGINT PRIMARY KEY, active BOOLEAN)");
        jdbc.execute("INSERT INTO unit_of_measure VALUES(1,TRUE)");
        jdbc.execute("CREATE TABLE strategic_cycle(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(255), start_date DATE, end_date DATE, cadence_days INT, status VARCHAR(24), version BIGINT DEFAULT 0, created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP)");
        jdbc.execute("CREATE TABLE strategic_cycle_period(cycle_id BIGINT, period_id BIGINT, PRIMARY KEY(cycle_id,period_id))");
        jdbc.execute("CREATE TABLE metric_definition(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(255), unit_of_measure_id BIGINT, direction VARCHAR(16), source_description TEXT, version BIGINT DEFAULT 0, frequency_days INT, numerator_description TEXT, denominator_description TEXT, inclusion_rules TEXT, exclusion_rules TEXT, active BOOLEAN, created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP)");
        jdbc.execute("CREATE TABLE key_result(id BIGINT PRIMARY KEY, metric_definition_id BIGINT, active BOOLEAN)");
        service = new GovernanceV2Service(jdbc, mock(AuditService.class));
    }
    GovernanceV2Service.CycleWrite cycle(Long version) { return new GovernanceV2Service.CycleWrite("Ciclo", LocalDate.of(2026,1,1), LocalDate.of(2026,12,31), 30, "ACTIVE", List.of(1L), version); }
    GovernanceV2Service.MetricWrite metric(boolean active, Long version) { return new GovernanceV2Service.MetricWrite("Retención", 1L, "MAINTAIN", "Registro institucional", 30, null, null, null, null, active, version); }
    @Test void savesCycleWithPeriodsAndRejectsStaleVersion() {
        var saved = service.saveCycle(null, cycle(null));
        assertThat(saved.periodIds()).containsExactly(1L);
        var updated = service.saveCycle(saved.id(), cycle(saved.version()));
        assertThat(updated.version()).isEqualTo(saved.version()+1);
        assertThatThrownBy(() -> service.saveCycle(saved.id(), cycle(saved.version()))).isInstanceOf(BusinessException.class).hasMessage("VERSION_CONFLICT");
    }
    @Test void rejectsInvalidDatesAndPrematureClosure() {
        assertThatThrownBy(() -> service.saveCycle(null, new GovernanceV2Service.CycleWrite("C", LocalDate.of(2026,2,1), LocalDate.of(2026,1,1), 30, "DRAFT", List.of(), null))).hasMessage("INVALID_DATE_RANGE");
        assertThatThrownBy(() -> service.saveCycle(null, new GovernanceV2Service.CycleWrite("C", LocalDate.of(2026,1,1), LocalDate.of(2026,2,1), 30, "CLOSED", List.of(), null))).hasMessage("FINAL_REVIEW_REQUIRED");
        assertThat(service.cycles()).isEmpty();
    }
    @Test void metricCanBeEditedButNotDeactivatedWithActiveDependents() {
        var saved = service.saveMetric(null, metric(true,null));
        jdbc.update("INSERT INTO key_result VALUES(1,?,TRUE)", saved.id());
        var updated = service.saveMetric(saved.id(), metric(true,saved.version()));
        assertThat(updated.sourceDescription()).isEqualTo("Registro institucional");
        assertThatThrownBy(() -> service.saveMetric(saved.id(), metric(false,updated.version()))).hasMessage("ACTIVE_DEPENDENTS");
        assertThat(jdbc.queryForObject("SELECT active FROM metric_definition WHERE id=?", Boolean.class, saved.id())).isTrue();
    }
    @Test void rejectsMissingSourceAndInactiveUnit() {
        assertThatThrownBy(() -> service.saveMetric(null, new GovernanceV2Service.MetricWrite("M",1L,"INCREASE"," ",30,null,null,null,null,true,null))).hasMessage("SOURCE_REQUIRED");
        jdbc.update("UPDATE unit_of_measure SET active=FALSE");
        assertThatThrownBy(() -> service.saveMetric(null, metric(true,null))).hasMessage("INVALID_UNIT");
    }
}
