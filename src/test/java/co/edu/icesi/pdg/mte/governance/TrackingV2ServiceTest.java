package co.edu.icesi.pdg.mte.governance;
import co.edu.icesi.pdg.mte.audit.AuditService;
import co.edu.icesi.pdg.mte.security.ExternalUserContext;
import org.junit.jupiter.api.*;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import org.springframework.security.authentication.UsernamePasswordAuthenticationToken;
import org.springframework.security.core.authority.SimpleGrantedAuthority;
import org.springframework.security.core.context.SecurityContextHolder;
import java.math.BigDecimal;
import java.time.Instant;
import java.util.*;
import static org.assertj.core.api.Assertions.*;
import static org.mockito.Mockito.*;

class TrackingV2ServiceTest {
    JdbcTemplate jdbc; TrackingV2Service service;
    @BeforeEach void setup() {
        jdbc = new JdbcTemplate(new DriverManagerDataSource("jdbc:h2:mem:"+UUID.randomUUID()+";MODE=PostgreSQL;DB_CLOSE_DELAY=-1;DATABASE_TO_LOWER=TRUE", "sa", ""));
        jdbc.execute("CREATE TABLE professor(id BIGINT PRIMARY KEY, email VARCHAR, active BOOLEAN, department_id BIGINT, name VARCHAR)");
        jdbc.execute("INSERT INTO professor VALUES(1,'manager@test',TRUE,10,'Gestor')");
        jdbc.execute("CREATE TABLE objective(id BIGINT PRIMARY KEY, department_id BIGINT)");
        jdbc.execute("INSERT INTO objective VALUES(1,10),(2,20)");
        jdbc.execute("CREATE TABLE unit_of_measure(id BIGINT PRIMARY KEY, name VARCHAR, type VARCHAR, decimal_precision INT)");
        jdbc.execute("INSERT INTO unit_of_measure VALUES(1,'Porcentaje','PORCENTAJE',2)");
        jdbc.execute("CREATE TABLE key_result(id BIGINT PRIMARY KEY, name VARCHAR, objective_id BIGINT, unit_of_measure_id BIGINT, version BIGINT, active BOOLEAN, status VARCHAR)");
        jdbc.execute("INSERT INTO key_result VALUES(1,'Retención',1,1,0,TRUE,'ACTIVO'),(2,'Ajeno',2,1,0,TRUE,'ACTIVO')");
        jdbc.execute("ALTER TABLE key_result ADD COLUMN strategic_cycle_id BIGINT");
        jdbc.execute("CREATE TABLE kr_assignment(key_result_id BIGINT, professor_id BIGINT, ended_at TIMESTAMP)");
        jdbc.execute("CREATE TABLE kr_progress_entry(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, key_result_id BIGINT, progress_percent NUMERIC(5,2), status VARCHAR, comment TEXT, declared_by VARCHAR, declared_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP)");
        jdbc.execute("CREATE TABLE kr_measurement(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, key_result_id BIGINT, measured_value NUMERIC(12,4), observed_at TIMESTAMP WITH TIME ZONE, comment TEXT, registered_by VARCHAR, registered_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP, status VARCHAR DEFAULT 'ACTIVE', version BIGINT DEFAULT 0)");
        var context = new ExternalUserContext(1L,"manager","manager@test",List.of("MANAGER"),List.of(),1L,"Gestor","D");
        SecurityContextHolder.getContext().setAuthentication(new UsernamePasswordAuthenticationToken(context,null,List.of(new SimpleGrantedAuthority("ROLE_MANAGER"))));
        service = new TrackingV2Service(jdbc, mock(AuditService.class));
    }
    @AfterEach void cleanup() { SecurityContextHolder.clearContext(); }
    @Test void progressIsIndependentAndRejectsStaleVersion() {
        service.declareProgress(1,new TrackingV2Service.ProgressWrite(new BigDecimal("37"),"ON_TRACK","Avance",0L));
        assertThat(service.progress(1).get(0).get("progressPercent")).isEqualTo(new BigDecimal("37.00"));
        assertThat(service.measurements(1)).isEmpty();
        assertThatThrownBy(() -> service.declareProgress(1,new TrackingV2Service.ProgressWrite(BigDecimal.TEN,"ON_TRACK","",0L))).hasMessage("VERSION_CONFLICT");
        assertThat(service.progress(1)).hasSize(1);
    }
    @Test void measurementDoesNotDeclareProgressAndReturnsIsoTime() {
        var entry = service.measure(1,new TrackingV2Service.MeasurementWrite(new BigDecimal("74.5"),Instant.parse("2026-01-01T12:00:00Z"),"Registro"));
        assertThat(entry.get("observedAt")).isEqualTo("2026-01-01T12:00:00Z");
        assertThat(service.progress(1)).isEmpty();
        assertThatThrownBy(() -> service.measure(1,new TrackingV2Service.MeasurementWrite(new BigDecimal("101"),Instant.now(),""))).hasMessage("INVALID_MEASUREMENT");
    }
    @Test void otherDepartmentCannotReadOrWriteHistory() {
        assertThatThrownBy(() -> service.progress(2)).hasMessage("OUT_OF_SCOPE");
        assertThatThrownBy(() -> service.declareProgress(2,new TrackingV2Service.ProgressWrite(BigDecimal.TEN,"ON_TRACK","",0L))).hasMessage("OUT_OF_SCOPE");
        assertThat(jdbc.queryForObject("SELECT COUNT(*) FROM kr_progress_entry",Long.class)).isZero();
    }
    @Test void contributorCannotWriteUnassignedKr() {
        var auth = SecurityContextHolder.getContext().getAuthentication();
        SecurityContextHolder.getContext().setAuthentication(new UsernamePasswordAuthenticationToken(auth.getPrincipal(),null,List.of(new SimpleGrantedAuthority("ROLE_CONTRIBUTOR"))));
        assertThatThrownBy(() -> service.declareProgress(1,new TrackingV2Service.ProgressWrite(BigDecimal.TEN,"ON_TRACK","",0L))).hasMessage("FORBIDDEN");
    }
}
